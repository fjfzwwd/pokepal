def pick(key: str, pool: Dict[str, List[str]], fallback: List[str] | None = None) -> str:
    lst = pool.get(key) or fallback or IDLE
    return random.choice(lst)


def random_line(key: str) -> str:
    return pick(key, MOOD, IDLE)


def idle_line() -> str:
    return random.choice(IDLE)
